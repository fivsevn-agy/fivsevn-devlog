#!/usr/bin/env python3
"""Build the self-contained fieldlog archive, without contacting WordPress."""
from __future__ import annotations

import argparse
from dataclasses import dataclass
from datetime import datetime
from hashlib import sha256
from html import escape
import json
from pathlib import Path
import re
import shutil
from string import Template
from urllib.parse import quote, unquote, urlparse
from zoneinfo import ZoneInfo

import markdown
from PIL import Image
from bs4 import BeautifulSoup
from site_post_metadata import (is_published, metadata_view, published_datetime,
                                read_frontmatter, validate_metadata)

ROOT = Path(__file__).resolve().parents[1]
BASE = "/natsci/fieldlog/"
ORIGIN = "https://devlog.fivsevn.com"
SITE_TITLE = "devlog.natsci/fieldlog"
PAGE_SIZE = 11
MONTHS = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")
MARKER = "<!-- Generated by scripts/build_fieldlog.py; edit index.md and templates instead. -->"


@dataclass
class Entry:
    path: Path
    meta: dict
    body: str
    date: datetime
    url: str
    image_url: str
    width: int
    height: int


def read_entries(folder: Path) -> list[Entry]:
    entries, ids = [], set()
    manifest = folder / "site-data/history.json"
    order = {}
    if manifest.exists():
        order = {ident: i for i, ident in enumerate(json.loads(manifest.read_text())["order"])}
    for path in sorted(folder.glob("[0-9][0-9][0-9][0-9]/[0-9][0-9]/*/index.md")):
        raw, body = read_frontmatter(path)
        validate_metadata(raw, site="fieldlog", schema_dir=ROOT / "schemas")
        meta = metadata_view(raw)
        ident = str(meta.get("id", ""))
        if not ident or ident in ids or ident != path.parent.name:
            raise ValueError(f"{path}: id must be unique and match its folder")
        ids.add(ident)
        if not is_published(raw):
            continue
        date = published_datetime(raw)
        if not re.fullmatch(r"\d{12}", str(meta.get("observation_id", ""))):
            raise ValueError(f"{path}: observation_id must contain 12 digits")
        image = (path.parent / str(meta["image"])).resolve()
        if not image.is_relative_to((path.parent / "assets").resolve()) or not image.is_file():
            raise ValueError(f"{path}: image must exist inside this post's folder")
        with Image.open(image) as im:
            if image.suffix.lower() != ".webp" or im.format != "WEBP":
                raise ValueError(f"{path}: saved photos must be WebP; run scripts/normalize_fieldlog_images.py")
            width, height = im.size
            # Browsers apply EXIF orientation to the original image.
            if im.getexif().get(274) in {5, 6, 7, 8}:
                width, height = height, width
        relative = path.parent.relative_to(folder).as_posix()
        url = BASE + quote(relative, safe="/") + "/"
        image_url = BASE + quote(image.relative_to(folder.resolve()).as_posix(), safe="/")
        entries.append(Entry(path, meta, body.strip(), date, url, image_url, width, height))
    return sorted(entries, key=lambda e: (e.date, -order.get(str(e.meta["id"]), -1), str(e.meta["id"])), reverse=True)


def card(entry: Entry, detail: bool, return_url: str = BASE) -> str:
    m = entry.meta
    obs = escape(str(m["observation_id"]))
    date = escape(str(m["date"]))
    local_date = entry.date.astimezone(ZoneInfo("Asia/Shanghai"))
    default_title = f"{local_date.day} {MONTHS[local_date.month - 1]}, {local_date.year} {local_date:%H:%M}"
    label = escape(str(m.get("title") or "").strip() or default_title)
    annotation = ""
    controls = '<span aria-hidden="true">[-][□][X]</span>'
    if detail:
        controls = ('<span class="window-controls"><span aria-hidden="true">[-][□][</span>'
                    f'<a class="window-close" data-fieldlog-return href="{escape(return_url, quote=True)}" '
                    'aria-label="Close specimen and return to observation log">X</a>'
                    '<span aria-hidden="true">]</span></span>')
    if detail and entry.body:
        body = markdown.markdown(entry.body, extensions=["extra", "sane_lists"])
        annotation = f'<div class="annotation" id="annotation"><span aria-hidden="true">[</span><div class="annotation-body">{body}</div><span aria-hidden="true">]</span></div>\n<p class="dash">—</p>'
    return f'''<article class="specimen" id="obs-{escape(str(m['id']))}" aria-label="OBS {obs}">
  <div class="window-bar"><span class="window-title">Specimen Viewer</span>{controls}</div>
  <div class="window-body">
    <div class="row observation"><span>### OBS</span><span>–</span><span>057</span><time datetime="{date}">{obs}</time></div>
    <p class="dash">—</p>
    <p class="image-path">![image](assets/<span>{entry.date.year}</span>/OBS-<a href="{entry.url}" data-fieldlog-open aria-label="Open observation {obs}">{obs}</a>_raw.tif)</p>
    <figure><img src="{entry.image_url}" alt="{escape(str(m.get('alt') or m.get('title') or obs), quote=True)}" width="{entry.width}" height="{entry.height}" loading="lazy" decoding="async"></figure>
    <p class="dash">—</p>
    <div class="metadata">
      <div class="row"><span>Date:</span><time datetime="{date}">{date}</time></div>
      <div class="row"><span>Status:</span><span>{escape(str(m.get('archive_status') or 'Archived'))}</span></div>
      <div class="row"><span>Annotation Log:</span><span class="annotation-date">{label}</span></div>
    </div>
    <p class="dash">—</p>
    {annotation}
  </div>
</article>'''


def pagination(current: int, count: int) -> str:
    if count <= 1:
        return ""
    def url(page):
        return BASE if page == 1 else f"{BASE}page/{page}/"
    links = []
    if current > 1:
        links.append(f'<a class="pager-arrow" href="{url(current-1)}" rel="prev" aria-label="Previous Page">«</a>')
    for page in range(1, count + 1):
        links.append(f'<span aria-current="page">{page}</span>' if page == current else f'<a href="{url(page)}">{page}</a>')
    if current < count:
        links.append(f'<a class="pager-arrow" href="{url(current+1)}" rel="next" aria-label="Next Page">»</a>')
    return '<nav class="pagination" aria-label="Pagination">' + " ".join(links) + "</nav>"


def check_links(outputs: dict[str, bytes]) -> None:
    for path, content in outputs.items():
        if not path.endswith(".html"):
            continue
        soup = BeautifulSoup(content, "html.parser")
        for element in soup.select("[src], [href]"):
            value = element.get("src", element.get("href", ""))
            target = urlparse(value)
            if target.scheme or target.netloc:
                if element.has_attr("src") or element.name == "link" and element.get("rel") == ["stylesheet"]:
                    raise ValueError("External runtime asset: " + value)
                continue
            if not target.path:
                if target.fragment and not soup.find(id=unquote(target.fragment)):
                    raise ValueError(f"Missing anchor: {path} {value}")
                continue
            if not target.path.startswith(BASE):
                continue  # Links to other devlog modules belong to the parent build.
            relative = unquote(target.path[len(BASE):])
            destination = relative + "index.html" if not relative or relative.endswith("/") else relative
            if destination not in outputs:
                raise ValueError(f"Broken fieldlog link: {path} {value}")
            if target.fragment and destination.endswith(".html"):
                linked = BeautifulSoup(outputs[destination], "html.parser")
                if not linked.find(id=unquote(target.fragment)):
                    raise ValueError(f"Missing target anchor: {path} {value}")


def build(root: Path = ROOT, check=False, output: Path | None = None) -> dict:
    root = Path(root).resolve()
    folder = root / "natsci/fieldlog"
    output = Path(output or root / "_site/natsci/fieldlog").resolve()
    if root.is_relative_to(output) or output.is_relative_to(folder) or folder.is_relative_to(output):
        raise ValueError("Unsafe fieldlog output path")
    templates = root / "scripts/fieldlog_templates"
    page_template = Template((templates / "page.html").read_text(encoding="utf-8"))
    header = (templates / "header.html").read_text(encoding="utf-8")
    css = (folder / "ui/fieldlog.css").read_bytes()
    navigation = (folder / "ui/navigation.js").read_bytes()
    version = sha256(css + navigation).hexdigest()[:12]
    entries = read_entries(folder)
    archive_routes = {}
    for index, entry in enumerate(entries):
        number = index // PAGE_SIZE + 1
        archive_routes["obs-" + str(entry.meta["id"])] = (BASE if number == 1 else f"{BASE}page/{number}/") + "#" + quote("obs-" + str(entry.meta["id"]), safe="")
    route_data = '<script type="application/json" id="fieldlog-archive-map">' + json.dumps(archive_routes, ensure_ascii=False).replace("<", "\\u003c") + '</script>\n'
    outputs: dict[str, bytes] = {}
    def page(title, url, content, kind):
        html = page_template.substitute(title=escape(title), canonical=ORIGIN+url,
            css_version=version, content=content, kind=kind, marker=MARKER)
        return html.replace("</body>", route_data + "</body>").encode("utf-8")
    pages = max(1, (len(entries) + PAGE_SIZE - 1) // PAGE_SIZE)
    for number in range(1, pages + 1):
        url = BASE if number == 1 else f"{BASE}page/{number}/"
        path = "index.html" if number == 1 else f"page/{number}/index.html"
        cards = "\n".join(card(e, False) for e in entries[(number-1)*PAGE_SIZE:number*PAGE_SIZE])
        # Old page/N/#obs-ID bookmarks can reach a post after page-size changes.
        relocated = "".join(f'<a class="archive-relocation" id="{escape(anchor)}" href="{escape(target)}">Open observation {escape(anchor[4:])} →</a>'
                            for anchor, target in archive_routes.items() if target.split("#", 1)[0] != url)
        root_link = '<p class="root-link">[<a href="https://fivsevn.com/">Root Directory</a>]</p>'
        content = header + relocated + '<section class="observations" aria-label="Observation Log">' + cards + '</section>' + pagination(number, pages) + root_link
        outputs[path] = page(SITE_TITLE, url, content, "archive")
    for entry in entries:
        relative = entry.path.parent.relative_to(folder).as_posix()
        outputs[relative + "/index.html"] = page(f"OBS {entry.meta['observation_id']} · {SITE_TITLE}", entry.url,
            card(entry, True, archive_routes["obs-" + str(entry.meta["id"])]), "detail")
        for asset in (entry.path.parent / "assets").rglob("*"):
            if asset.is_file():
                with Image.open(asset) as im:
                    if asset.suffix.lower() != ".webp" or im.format != "WEBP":
                        raise ValueError(f"{asset}: saved photos must be WebP; run scripts/normalize_fieldlog_images.py")
                outputs[asset.relative_to(folder).as_posix()] = asset.read_bytes()
    for asset in (folder / "ui").rglob("*"):
        if asset.is_file():
            outputs[asset.relative_to(folder).as_posix()] = asset.read_bytes()
    check_links(outputs)
    outputs[".nojekyll"] = b""
    receipt = {"posts": len(entries), "pages": pages, "archive_pages": pages,
               "base_path": BASE.rstrip("/"), "ids": [e.meta["id"] for e in entries],
               "files": {path: sha256(data).hexdigest() for path, data in sorted(outputs.items())}}
    outputs["build-receipt.json"] = (json.dumps(receipt, ensure_ascii=False, indent=2) + "\n").encode()
    existing = {p.relative_to(output).as_posix(): p for p in output.rglob("*") if p.is_file()} if output.exists() else {}
    changed = [path for path, data in outputs.items() if path not in existing or existing[path].read_bytes() != data]
    stale = [path for path in existing if path not in outputs and path != ".verified.json"]
    if check and (changed or stale):
        raise ValueError("Generated pages are stale: " + ", ".join(changed + stale))
    if not check:
        if output.exists():
            shutil.rmtree(output)
        output.mkdir(parents=True)
        for path, data in outputs.items():
            destination = output / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(data)
    return dict(receipt, changed=len(changed), removed=len(stale), output=str(output))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = build(args.root.resolve(), args.check, args.output)
    print(json.dumps({key: result[key] for key in ("posts", "pages", "changed", "removed", "output")}))


if __name__ == "__main__":
    main()
